const assert=require('node:assert/strict');
const fs=require('node:fs');
assert.ok(fs.existsSync(__dirname+'/web/track-timeline.js'),'Track timeline module must exist');
const {Timeline,outputTime}=require('./web/track-timeline.js');
const analysis={duration:4,bpm:120,hits:[.5,1,1.5],bands:[[.2,.3,.4,.2],[.8,.1,.2,.4]],step:2};
const timeline=new Timeline(analysis,'beat',100);
assert.equal(timeline.sample(.55).active,true);
assert.equal(timeline.sample(.65).active,false);
assert.equal(timeline.sample(.25).beatIndex,0);
assert.equal(timeline.sample(1.05).beatIndex,2);
assert.equal(timeline.sample(1.05).lastHit,1);
assert.equal(timeline.sample(3).bass,.8);
const first=timeline.take(0,.8);assert.deepEqual(first.filter(x=>x.hit).map(x=>x.time),[.5]);
assert.equal(timeline.take(.3,.8).length,0,'No duplicate scheduled events');
timeline.seek(.9);assert.deepEqual(timeline.take(.9,1.2).filter(x=>x.hit).map(x=>x.time),[1]);
timeline.seek(0);assert.deepEqual(timeline.take(1.2,1.7).filter(x=>x.hit).map(x=>x.time),[1.5],'Skip stale events after stalled tab');
assert.equal(outputTime(2,{currentTime:1,outputLatency:.2,getOutputTimestamp:()=>({contextTime:.8,performanceTime:1000})},1200,270),2200);
assert.equal(outputTime(2,{currentTime:1,outputLatency:.2},1200,270),2400);
assert.equal(outputTime(2,{currentTime:1},1200,270),2470);
assert.equal(outputTime(2,{currentTime:1,getOutputTimestamp:()=>({contextTime:.8,performanceTime:1000})},1200,270,300),2500,'Measured acoustic timing replaces output estimate');
console.log('Track timeline checks passed');
